#include <iostream> 
#include <cmath>   
using namespace std;

int main() {
    setlocale(LC_ALL, "Russian");
    double a, b, c; // Объявляем переменные для коэффициентов уравнения
    cout << "Введите a, b, c: "; // Просим пользователя ввести коэффициенты
    cin >> a >> b >> c;

    if (a == 0) { // Проверяем, равен ли коэффициент 'a' нулю (тогда уравнение не биквадратное)
        cout << "Ошибка: a не может быть равно 0" << endl;
        return 1;
    }

    double D = b * b - 4 * a * c; // Вычисляем дискриминант квадратного уравнения относительно t (x^2)
    cout << "Дискриминант D = " << D << endl; // Выводим значение дискриминанта

    if (D < 0) { // Если дискриминант меньше нуля
        cout << "Нет действительных корней (D < 0)" << endl; // Корней нет
    }
    else if (D == 0) { // Если дискриминант равен нулю
        double t = -b / (2 * a); // Вычисляем единственный корень t
        if (t < 0) { // Если t отрицательное, то x^2 = t не имеет корней
            cout << "Нет действительных корней (t < 0)" << endl;
        }
        else if (t == 0) { // Если t = 0, то x = 0
            cout << "Один корень: x = 0" << endl;
        }
        else { // Если t > 0, то два корня
            cout << "Два корня: x1 = " << sqrt(t) << ", x2 = " << -sqrt(t) << endl;
        }
    }
    else { // Если дискриминант больше нуля
        double t1 = (-b + sqrt(D)) / (2 * a); // Вычисляем первый корень t1
        double t2 = (-b - sqrt(D)) / (2 * a); // Вычисляем второй корень t2

        // Далее проверяем каждый корень t: если он >= 0, из него можно извлечь корень x
        if (t1 >= 0) { // Если t1 неотрицательное
            cout << "Корень x1 = " << sqrt(t1) << ", x2 = " << -sqrt(t1) << endl; // Находим два корня x
        }
        if (t2 >= 0) { // Если t2 неотрицательное
            cout << "Корень x3 = " << sqrt(t2) << ", x4 = " << -sqrt(t2) << endl; // Находим еще два корня x
        }
        if (t1 < 0 && t2 < 0) { // Если оба корня t оказались отрицательными
            cout << "Нет действительных корней (t1 и t2 < 0)" << endl; // То корней x нет
        }
    }
    return 0;
}