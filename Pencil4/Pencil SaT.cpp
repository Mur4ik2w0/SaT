#include <iostream>
#include <cmath>
using namespace std;

int main() {
    setlocale(LC_ALL, "Russian");
    int n;
    cout << "Введите количество элементов n: ";
    cin >> n;
    if (n <= 0) {
        cout << "Ошибка: размер массива должен быть больше 0" << endl;
        return 1;
    }
    double* arr = new double[n];// Динамически выделяем память под массив из n вещественных чисел
    double sum = 0;// Объявляем переменную для накопления суммы квадратов и обнуляем её
    for (int i = 0; i < n; i++) {// Выводим приглашение для ввода i-го элемента
        cout << "arr[" << i << "] = ";// Считываем значение с клавиатуры и записываем в i-ю ячейку массива
        cin >> arr[i];
        sum += arr[i] * arr[i];// Возводим i-й элемент в квадрат и добавляем к общей сумме
    }
    double rms = sqrt(sum / n);// Вычисляем среднеквадратическое значение: корень из (сумма / n)
    cout << "Среднеквадратическое значение: " << rms << endl;
    delete[] arr;// Освобождаем динамически выделенную память (чтобы не было утечек)
    return 0;
}
